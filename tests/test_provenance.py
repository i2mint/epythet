def test_compare_versions():
    assert compare_versions("0.2.4", "0.2.5") == "behind"
    assert compare_versions("0.3.0", "0.2.5") == "ahead"
    assert compare_versions("1.0", "1.0.0") == "same"
    assert compare_versions("not-a-version", "1.0") == "unknown"


def test_pypi_lookup_failure_degrades_to_not_checked(monkeypatch):
    import epythet.provenance as prov

    def boom(name, *, timeout):
        raise OSError("network is unreachable")

    monkeypatch.setattr(prov, "pypi_latest_version", boom)
    info = pypi_info("pkg", "1.0")
    assert info == {
        "checked": False,
        "latest": None,
        "relation": "unknown",
        "error": "OSError: network is unreachable",
    }


def test_pypi_behind_and_ahead_notes(monkeypatch, repo):
    import epythet.provenance as prov

    monkeypatch.setattr(prov, "pypi_latest_version", lambda name, *, timeout: "0.0.2")
    info = collect_build_info(load_config(repo), check_pypi=True)
    assert info["pypi"] == {
        "checked": True,
        "latest": "0.0.2",
        "relation": "behind",
        "error": None,
    }
    assert info["alignment"]["aligned"] is False
    assert "behind the latest release on PyPI (0.0.2)" in info["alignment"]["notes"][0]
    page = render_about_page(info)
    assert "newer than the documented version (0.0.1)" in page
    monkeypatch.setattr(prov, "pypi_latest_version", lambda name, *, timeout: None)
    info = collect_build_info(load_config(repo), check_pypi=True)
    assert (
        info["pypi"]["relation"] == "unknown" and info["alignment"]["aligned"] is True
    )
    assert "is not on PyPI" in render_about_page(info)


def test_pypi_env_switch(monkeypatch, repo):
    import epythet.provenance as prov

    calls = []
    monkeypatch.setattr(
        prov, "pypi_latest_version", lambda name, *, timeout: calls.append(name)
    )
    collect_build_info(load_config(repo), environ={"EPYTHET_PYPI_CHECK": "0"})
    assert calls == []
    collect_build_info(load_config(repo), environ={})
    assert calls == ["pkg"]


