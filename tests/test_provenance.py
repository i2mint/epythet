def test_record_schema_is_stable_and_json_serialisable(repo):
    info = collect_build_info(load_config(repo), check_pypi=False)
    assert set(info) == EXPECTED_KEYS and info["schema_version"] == SCHEMA_VERSION
    assert set(info["package"]) == {"name", "version", "display_name", "source"}
    assert set(info["git"]) == {
        "available",
        "commit",
        "short_commit",
        "branch",
        "tags",
        "dirty",
        "remote_url",
        "commit_url",
        "error",
    }
    assert set(info["ci"]) == {
        "provider",
        "repository",
        "sha",
        "sha_in_history",
        "ref",
        "ref_name",
        "run_id",
        "run_url",
        "server_url",
    }
    assert set(info["tools"]) == {"epythet", "sphinx", "docutils", "python"}
    assert set(info["config"]) == {
        "theme",
        "html_theme",
        "accent",
        "mode",
        "api_generator",
        "ignore",
        "agent_outputs",
        "aggregates",
        "ai_artifacts",
        "provenance",
        "docs_dir",
    }
    assert set(info["site"]) == {"modules_documented", "objects_documented"}
    assert set(info["pypi"]) == {"checked", "latest", "relation", "error"}
    assert set(info["alignment"]) == {"aligned", "notes"}
    assert info["package"]["source"] == "pyproject.toml"
    assert info["built_at"].endswith("Z")
    assert info["alignment"] == {"aligned": True, "notes": []}
    assert "git clone git@github.com:org/pkg.git && cd pkg" in info["reproduce"]
    assert "git checkout " + info["git"]["commit"] in info["reproduce"]
    json.dumps(info)  # every value is plain JSON


def test_record_without_git_says_so(make_project):
    info = collect_build_info(load_config(make_project("pkg", {})), check_pypi=False)
    assert info["git"]["available"] is False
    assert info["alignment"]["aligned"] is None
