"""Unit tests for :mod:`epythet.provenance`: collection, degradation, rendering.

The Sphinx smoke build in ``test_build.py`` covers the rendered footer, page
and JSON; here the record itself is exercised without a build: a git fixture
(clean, dirty, tagged, detached), the CI environment, no git at all, the JSON
key set that ``schema_version`` promises, and the ``provenance`` config seam.
"""

import json
import subprocess
