@pytest.mark.parametrize(
    "value, expected",
    [("true", True), ("false", False), ('"minimal"', "minimal")],
)
def test_provenance_key_from_pyproject(tmp_path, value, expected):
    (tmp_path / "pyproject.toml").write_text(
        f'[project]\nname = "x"\n[tool.epythet]\nprovenance = {value}\n'
    )
    assert load_config(tmp_path).provenance == expected


@pytest.mark.parametrize(
    "value, expected",
    [("true", True), ("off", False), ("Minimal", "minimal")],
)
def test_provenance_key_from_setup_cfg(tmp_path, value, expected):
    (tmp_path / "setup.cfg").write_text(
        f"[metadata]\nname = x\n[tool.epythet]\nprovenance = {value}\n"
    )
    assert load_config(tmp_path).provenance == expected


