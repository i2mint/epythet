def test_page_builds_in_the_site(repo):
    from epythet.build import build

    cfg = load_config(repo)
    scaffold(cfg, verbose=False)
    html = build(cfg, "html")
    page = (html / "ai-agents.html").read_text(encoding="utf-8")
    assert "For AI agents" in page
    assert 'href="https://org.github.io/acme/llms.txt"' in page
    assert "ai-agents" in (html / "index.html").read_text(encoding="utf-8")
    # The page has its own agent twin; the install line is intact there (the
    # HTML splits it into highlighted spans).
    twin = (html / "ai-agents.html.md").read_text(encoding="utf-8")
    assert "gh skill install org/acme acme-use --agent claude-code" in twin
