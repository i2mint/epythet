"""Tests for the AI artifacts: shipped skills and agents, discovery, and the generated page.

Three concerns, in order: the artifacts epythet itself ships are spec-valid
(the Agent Skills frontmatter rules, and the subagent frontmatter), discovery
finds every artifact kind from a fixture repository (including through the
``.claude/skills`` symlink bridge, without duplicates), and the "For AI agents"
page is generated by default and builds in the smoke site.
"""

import os
