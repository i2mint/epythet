REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / "epythet" / "data" / "skills"
AGENTS_DIR = REPO_ROOT / "epythet" / "data" / "agents"

SHIPPED_SKILLS = {
    "epythet-setup",
    "epythet-pages",
    "epythet-docstring-style",
    "epythet-validate",
    "epythet-repair-migrate",
    "epythet-theme",
    "epythet-ai-artifacts",
}
SHIPPED_AGENTS = {"docs-reviewer", "docs-migrator"}

#: The Agent Skills spec: the only top-level frontmatter keys allowed.
SPEC_KEYS = {
    "name",
    "description",
    "license",
    "compatibility",
    "metadata",
    "allowed-tools",
}
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


# --------------------------------------------------------------------------
# The shipped artifacts are spec-valid
# --------------------------------------------------------------------------


def test_every_expected_skill_ships():
    assert {p.name for p in SKILLS_DIR.iterdir() if p.is_dir()} == SHIPPED_SKILLS


@pytest.mark.parametrize(
    "skill_dir", sorted(SKILLS_DIR.iterdir()), ids=lambda p: p.name
)
def test_skill_frontmatter_is_spec_clean(skill_dir):
    skill_md = skill_dir / "SKILL.md"
    assert skill_md.is_file()
    text = skill_md.read_text(encoding="utf-8")
    meta = parse_frontmatter(text)
    assert meta, "SKILL.md needs a YAML frontmatter"
    assert set(meta) <= SPEC_KEYS, f"non-spec keys: {set(meta) - SPEC_KEYS}"
    assert meta["name"] == skill_dir.name
    assert NAME_RE.match(meta["name"]) and len(meta["name"]) <= 64
    assert 1 <= len(meta["description"]) <= 1024
    assert meta["metadata"]["audience"] in ("users", "both")
    if "allowed-tools" in meta:
        assert isinstance(meta["allowed-tools"], str)
    body = text.split("---", 2)[2]
    assert body.count("\n") < 500, (
        "keep SKILL.md under 500 lines; push detail to references/"
    )
    assert body.strip(), "SKILL.md needs a body"


@pytest.mark.parametrize(
    "skill_dir", sorted(SKILLS_DIR.iterdir()), ids=lambda p: p.name
)
def test_skill_references_exist(skill_dir):
    """Relative links inside a SKILL.md point at files that ship with it."""
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    for target in re.findall(r"\]\((?!https?://|#)([^)]+)\)", text):
        if "/" not in target and "." not in target:
            continue  # prose mentioning the `[text](url)` pattern, not a link
        assert (skill_dir / target).is_file(), f"{skill_dir.name}: missing {target}"


def test_every_expected_agent_ships_with_frontmatter():
    agents = {p.stem: parse_frontmatter(p.read_text()) for p in AGENTS_DIR.glob("*.md")}
    assert set(agents) == SHIPPED_AGENTS
    for name, meta in agents.items():
        assert meta["name"] == name
        assert len(meta["description"]) > 40
        assert meta["tools"]


def test_claude_code_bridge_symlinks_point_at_the_shipped_files():
    """One relative symlink per artifact in .claude/, never real copies."""
    for name in SHIPPED_SKILLS:
        link = REPO_ROOT / ".claude" / "skills" / name
        assert link.is_symlink(), f".claude/skills/{name} must be a symlink"
        assert not os.path.isabs(os.readlink(link))
        assert link.resolve() == (SKILLS_DIR / name).resolve()
    for name in SHIPPED_AGENTS:
        link = REPO_ROOT / ".claude" / "agents" / f"{name}.md"
        assert link.is_symlink()
        assert link.resolve() == (AGENTS_DIR / f"{name}.md").resolve()


def test_skill_cli_validator_agrees_if_installed():
    skill = pytest.importorskip("skill")
    for skill_dir in SKILLS_DIR.iterdir():
        assert skill.validate(str(skill_dir)) == [], skill_dir.name


