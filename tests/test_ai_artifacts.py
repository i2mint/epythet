def test_frontmatter_fallback_parser_matches_yaml():
    text = SKILL_MD.format(name="x")
    expected = {
        "name": "x",
        "description": "Use x for things.",
        "metadata": {"audience": "users"},
    }
    assert parse_frontmatter(text) == expected
    from epythet.ai_artifacts import _parse_simple_yaml

    block = text.split("---")[1].strip("\n")
    assert _parse_simple_yaml(block) == expected


