SKILL_MD = "---\nname: {name}\ndescription: >-\n  Use {name} for things.\nmetadata:\n  audience: users\n---\n\n# {name}\n"
AGENT_MD = "---\nname: {name}\ndescription: Does {name} work.\ntools: Bash, Read\n---\n\nPrompt.\n"


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


@pytest.fixture
def repo(tmp_path) -> Path:
    """A repository with every artifact kind, plus the .claude symlink bridge."""
    root = tmp_path / "acme"
    _write(
        root / "pyproject.toml",
        '[project]\nname = "acme"\nversion = "1.0"\n[project.urls]\nHomepage = "https://github.com/org/acme"\n',
    )
    _write(root / "acme" / "__init__.py", '"""Acme."""\n')
    _write(
        root / "acme" / "data" / "skills" / "acme-use" / "SKILL.md",
        SKILL_MD.format(name="acme-use"),
    )
    _write(
        root / "skills" / "acme-dev-release" / "SKILL.md",
        SKILL_MD.format(name="acme-dev-release"),
    )
    _write(
        root / ".claude" / "skills" / "acme-local" / "SKILL.md",
        SKILL_MD.format(name="acme-local"),
    )
    (root / ".claude" / "skills" / "acme-use").symlink_to(
        Path("../../acme/data/skills/acme-use")
    )
    _write(
        root / "acme" / "data" / "agents" / "acme-helper.md",
        AGENT_MD.format(name="acme-helper"),
    )
    _write(
        root / ".claude" / "agents" / "acme-local-agent.md",
        AGENT_MD.format(name="acme-local-agent"),
    )
    (root / ".claude" / "agents" / "acme-helper.md").symlink_to(
        Path("../../acme/data/agents/acme-helper.md")
    )
    _write(root / "CLAUDE.md", "# Acme\n")
    _write(root / "AGENTS.md", "# Agents\n")
    _write(root / ".cursor" / "rules" / "acme.mdc", "rule\n")
    _write(root / ".codex" / "config.toml", "x = 1\n")
