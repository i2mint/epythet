def test_epythet_documents_its_own_artifacts():
    cfg = load_config(REPO_ROOT)
    found = discover_artifacts(REPO_ROOT, package_dir=cfg.package_dir)
    assert {s.name for s in found.skills} == SHIPPED_SKILLS
    assert all(s.shipped and s.installable for s in found.skills)
    assert {a.name for a in found.subagents} == SHIPPED_AGENTS
    assert ".claude/CLAUDE.md" in {f.source for f in found.instruction_files}
    page = ai_artifacts_page(cfg)
    assert (
        "gh skill install i2mint/epythet epythet-setup --agent claude-code"
        in page.content
    )
    assert "https://i2mint.github.io/epythet/epythet.md" in page.content


